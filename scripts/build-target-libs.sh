#!/bin/sh
# build-target-libs.sh — cross-build the target library bundle (lib/<arch>).
#
# Usage: build-target-libs.sh <aarch64|armhf>
#
# Produces, for the given arch:
#   lib/<arch>/libraylib.a          raylib 5.5, PLATFORM_DRM + GRAPHICS_API_OPENGL_ES2
#   lib/<arch>/libportaudio.a       PortAudio 19.7.0 with the ALSA backend
#   lib/<arch>/libkissfft-float.a   kissfft (float)
#   lib/<arch>/stub/*.so            link-time-only stubs for the libraries the
#                                   device provides at runtime (libEGL.so.1,
#                                   libGLESv2.so.2, libgbm.so.1, libdrm.so.2,
#                                   libasound.so.2)
#   include/<arch>/*.h              the matching headers
#
# The bundle is committed to the repo, exactly like lib/arm/ is today.
#
# Why the stubs: the target's GL/GBM/DRM/ALSA stack lives in the device's
# userspace (mesa, alsa-lib). A cross build cannot link against it because
# the cross sysroot has no aarch64 copy of those shared libraries, and
# shipping foreign distro builds of them would be worse than not shipping
# them at all. So the bundle ships *stubs*: shared objects with the right
# SONAME and the right exported symbol names, but no code. They satisfy the
# link, and the loader resolves the symbols from the device's real
# libraries at run time (the SONAME is what the loader looks for).
#
# Host requirements: the cross toolchain (aarch64-linux-gnu-gcc), git, and
# the host's EGL/GLES2/GBM/DRM/ALSA development headers and shared
# libraries (they are only used for their headers and symbol lists).
set -eu

arch=${1:-}
case "$arch" in
    aarch64) host=aarch64-linux-gnu ;;
    armhf)   host=arm-linux-gnueabihf ;;
    *) echo "usage: $0 <aarch64|armhf>" >&2; exit 64 ;;
esac

cc=$host-gcc
ar=$host-ar
strip=$host-strip

for t in "$cc" "$ar"; do
    command -v "$t" >/dev/null 2>&1 || {
        echo "error: $t not found (install the $host cross toolchain)" >&2
        exit 1
    }
done

repo_root=$(cd "$(dirname "$0")/.." && pwd)
export SPECTRAX_REPO_ROOT="$repo_root"
cd "$repo_root"

work="$repo_root/build-libs/$arch"
out_lib="$repo_root/lib/$arch"
out_inc="$repo_root/include/$arch"
stub_dir="$out_lib/stub"
mkdir -p "$work" "$out_lib" "$out_inc" "$stub_dir"

# --- host header overlay -----------------------------------------------------
# The cross compiler does not search /usr/include (correctly: mixing the
# host's headers with the target's libc headers breaks struct layouts).
# Only the handful of arch-independent library headers are needed, so they
# are symlinked into one overlay directory and passed with -I.
sysinclude="$work/sysinclude"
mkdir -p "$sysinclude"
link_header() {
    src=$1
    [ -e "$src" ] || { echo "error: missing host header: $src" >&2; exit 1; }
    ln -sfn "$src" "$sysinclude/$(basename "$src")"
}
for d in EGL GLES2 KHR alsa; do
    [ -d "/usr/include/$d" ] || { echo "error: missing /usr/include/$d" >&2; exit 1; }
    ln -sfn "/usr/include/$d" "$sysinclude/$d"
done
for h in gbm.h xf86drm.h xf86drmMode.h; do
    link_header "/usr/include/$h"
done
for h in drm.h drm_mode.h drm_fourcc.h drm_sarea.h; do
    link_header "/usr/include/libdrm/$h"
done

# --- link-time stubs ---------------------------------------------------------
# make_stub <host .so> <soname> <output .so>
make_stub() {
    src=$1
    soname=$2
    out=$3
    [ -f "$src" ] || { echo "error: missing host library: $src" >&2; exit 1; }
    workdir="$work/stub-$soname"
    mkdir -p "$workdir"
    {
        echo "/* Generated by scripts/build-target-libs.sh -- link-time stub."
        echo " * The device provides the real $soname at run time. */"
        nm -D --defined-only "$src" 2>/dev/null | awk '
            NF >= 3 {
                type = $2; name = $3;
                sub(/@.*/, "", name);
                if (name !~ /^[A-Za-z_][A-Za-z0-9_]*$/) next;
                if (type ~ /^[TtWwVvIi]$/) print "void " name "(void) {}";
                else print "char " name "[64];";
            }' | sort -u
    } > "$workdir/stub.c"
    "$cc" -shared -fPIC -O0 -o "$out" -Wl,-soname,"$soname" "$workdir/stub.c"
    echo "  stub $out -> $soname"
}

host_libdir=$(pkg-config --variable=libdir egl 2>/dev/null || echo /usr/lib64)
[ -d "$host_libdir" ] || host_libdir=/usr/lib
make_stub "$host_libdir/libEGL.so.1"      libEGL.so.1      "$stub_dir/libEGL.so"
make_stub "$host_libdir/libGLESv2.so.2"  libGLESv2.so.2  "$stub_dir/libGLESv2.so"
make_stub "$host_libdir/libgbm.so.1"     libgbm.so.1     "$stub_dir/libgbm.so"
make_stub "$host_libdir/libdrm.so.2"     libdrm.so.2     "$stub_dir/libdrm.so"
make_stub "$host_libdir/libasound.so.2"  libasound.so.2  "$stub_dir/libasound.so"

# --- raylib ------------------------------------------------------------------
if [ ! -d "$work/raylib" ]; then
    git clone --depth 1 --branch 5.5 https://github.com/raysan5/raylib.git "$work/raylib"
fi
echo "building raylib for $arch"
rm -f "$work"/raylib-obj/*.o
mkdir -p "$work/raylib-obj"
# PLATFORM_DRM replaces GLFW with a DRM/KMS + GBM + EGL backend, which is the
# only raylib platform that can drive a handheld's panel without X11.
for f in rcore rtextures rtext rshapes rmodels raudio utils; do
    "$cc" -c -O2 \
        -DPLATFORM_DRM -DGRAPHICS_API_OPENGL_ES2 -DEGL_NO_X11 -D_GNU_SOURCE \
        -Werror=implicit-function-declaration \
        -I"$work/raylib/src" -I"$sysinclude" \
        -o "$work/raylib-obj/$f.o" "$work/raylib/src/$f.c"
done
"$ar" rcs "$out_lib/libraylib.a" "$work"/raylib-obj/*.o
cp "$work/raylib/src/raylib.h" "$work/raylib/src/raymath.h" "$out_inc/"

# --- PortAudio (ALSA backend) -----------------------------------------------
if [ ! -d "$work/portaudio" ]; then
    git clone --depth 1 --branch v19.7.0 https://github.com/PortAudio/portaudio.git "$work/portaudio"
fi
echo "building portaudio for $arch"
pc_dir="$work/pkgconfig"
mkdir -p "$pc_dir"
cat > "$pc_dir/alsa.pc" <<EOF
prefix=/usr
exec_prefix=\${prefix}
libdir=$stub_dir
includedir=$sysinclude

Name: alsa
Description: ALSA library (link-time stub used for cross builds)
Version: 1.2.16
Libs: -L\${libdir} -lasound
Cflags: -I\${includedir}
EOF
cd "$work/portaudio"
# The ALSA backend is checked with AC_CHECK_LIB, so the stub's directory has
# to be on the library path: LIBS carries it for the link tests.
if [ ! -f "$work/.portaudio-configured" ] ||
   ! grep -q -- "-DPA_USE_ALSA=1" "$work/portaudio/Makefile" 2>/dev/null ||
   ! grep -q -- "-I$sysinclude" "$work/portaudio/Makefile" 2>/dev/null; then
    PKG_CONFIG_PATH="$pc_dir" \
    CPPFLAGS="-I$sysinclude" \
    CFLAGS="-O2 -I$sysinclude" \
    LIBS="-L$stub_dir -lasound" \
    ./configure --host="$host" --with-alsa \
        --without-oss --without-jack --without-sndio --without-pulse \
        --without-asio --without-coreaudio --without-wdm --without-dsound \
        --disable-shared --enable-static --prefix="$work/portaudio-install" \
        > "$work/portaudio-configure.log" 2>&1 || {
            echo "error: portaudio configure failed; see $work/portaudio-configure.log" >&2
            tail -20 "$work/portaudio-configure.log" >&2
            exit 1
        }
    grep -q -- "-DPA_USE_ALSA=1" "$work/portaudio/Makefile" 2>/dev/null || {
        echo "error: portaudio configured without the ALSA backend" >&2
        grep -A3 'Configuration summary' "$work/portaudio-configure.log" >&2
        exit 1
    }
    touch "$work/.portaudio-configured"
fi
make -j"$(nproc)" > "$work/portaudio-make.log" 2>&1 || {
    echo "error: portaudio build failed; see $work/portaudio-make.log" >&2
    tail -20 "$work/portaudio-make.log" >&2
    exit 1
}
cp "$work/portaudio/lib/.libs/libportaudio.a" "$out_lib/"
cp "$work/portaudio/include/portaudio.h" "$out_inc/"

# --- kissfft -----------------------------------------------------------------
if [ ! -d "$work/kissfft" ]; then
    git clone --depth 1 https://github.com/mborgerding/kissfft.git "$work/kissfft"
fi
echo "building kissfft for $arch"
mkdir -p "$work/kissfft-obj"
# Compiled against the repository's own headers so the archive matches the
# ABI the application sees (include/kiss_fft.h, include/kiss_fftr.h).
"$cc" -c -O3 -ffast-math -I"$repo_root/include" -I"$work/kissfft" \
    -o "$work/kissfft-obj/kiss_fft.o"  "$work/kissfft/kiss_fft.c"
"$cc" -c -O3 -ffast-math -I"$repo_root/include" -I"$work/kissfft" \
    -o "$work/kissfft-obj/kiss_fftr.o" "$work/kissfft/kiss_fftr.c"
"$ar" rcs "$out_lib/libkissfft-float.a" "$work"/kissfft-obj/*.o

echo "built lib/$arch"
ls -la "$out_lib"
ls -la "$stub_dir"
